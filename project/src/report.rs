/// Formats a number with `sig` significant digits, switching to ×10ⁿ
/// notation for very small or large magnitudes; Turkish uses a decimal comma.
pub fn fmt_num(x: f64, sig: usize, lang: Lang) -> String {
    let s = if !x.is_finite() {
        if x.is_nan() {
            "—".to_string()
        } else {
            "∞".to_string()
        }
    } else if x == 0.0 {
        "0".to_string()
    } else {
        let mut e = x.abs().log10().floor() as i32;
        // Rounding may carry into the next decade (9.999 → 10.0).
        let scale = 10f64.powi(sig as i32 - 1 - e);
        if (x.abs() * scale).round() >= 10f64.powi(sig as i32) {
            e += 1;
        }
        if (-4..7).contains(&e) {
            let decimals = (sig as i32 - 1 - e).max(0) as usize;
            format!("{x:.decimals$}")
        } else {
            let m = x / 10f64.powi(e);
            format!("{m:.prec$} × 10{}", superscript(e), prec = sig.saturating_sub(1))
        }
    };
    match lang {
        Lang::Tr => s.replace('.', ","),
        Lang::En => s,
    }
}

fn superscript(e: i32) -> String {
    e.to_string()
        .chars()
        .map(|c| match c {
            '-' => '⁻',
            '0' => '⁰',
            '1' => '¹',
            '2' => '²',
            '3' => '³',
            '4' => '⁴',
            '5' => '⁵',
            '6' => '⁶',
            '7' => '⁷',
            '8' => '⁸',
            '9' => '⁹',
            other => other,
        })
        .collect()
}

/// Formats an input value as given (shortest round-trip representation).
fn fmt_given(x: f64, lang: Lang) -> String {
    let s = if x != 0.0 && !(1e-6..1e9).contains(&x.abs()) {
        let t = format!("{x:e}");
        match t.split_once('e') {
            Some((m, e)) => format!("{m} × 10{}", superscript(e.parse().unwrap_or(0))),
            None => t,
        }
    } else {
        format!("{x}")
    };
    match lang {
        Lang::Tr => s.replace('.', ","),
        Lang::En => s,
    }
}

/// A percentage: "95.45 %" in English, "%95,45" in Turkish (TS 1212 usage).
fn fmt_pct(fraction: f64, sig: usize, lang: Lang, trim: bool) -> String {
    let mut v = fmt_num(100.0 * fraction, sig, lang);
    if trim && v.contains(['.', ',']) && !v.contains('×') {
        v = v.trim_end_matches('0').trim_end_matches(['.', ',']).to_string();
    }
    match lang {
        Lang::En => format!("{v} %"),
        Lang::Tr => format!("%{v}"),
    }
}

fn dist_name(d: &DistributionSpec, lang: Lang) -> &'static str {
    use DistributionSpec::*;
    match (d, lang) {
        (Constant { .. }, Lang::En) => "constant",
        (Constant { .. }, Lang::Tr) => "sabit",
        (Normal { .. }, Lang::En) => "normal",
        (Normal { .. }, Lang::Tr) => "normal",
        (T { .. }, Lang::En) => "t (scaled, shifted)",
        (T { .. }, Lang::Tr) => "t (ölçekli, kaydırılmış)",
        (Rectangular { .. }, Lang::En) => "rectangular",
        (Rectangular { .. }, Lang::Tr) => "dikdörtgen",
        (Triangular { .. }, Lang::En) => "triangular",
        (Triangular { .. }, Lang::Tr) => "üçgen",
        (Arcsine { .. }, Lang::En) => "arc sine (U-shaped)",
        (Arcsine { .. }, Lang::Tr) => "ark sinüs (U biçimli)",
        (Trapezoidal { .. }, Lang::En) => "trapezoidal",
        (Trapezoidal { .. }, Lang::Tr) => "yamuk",
        (CurvilinearTrapezoid { .. }, Lang::En) => "curvilinear trapezoid",
        (CurvilinearTrapezoid { .. }, Lang::Tr) => "eğrisel yamuk",
        (Exponential { .. }, Lang::En) => "exponential",
        (Exponential { .. }, Lang::Tr) => "üstel",
        (Gamma { .. }, Lang::En) => "gamma",
        (Gamma { .. }, Lang::Tr) => "gama",
        (TypeA { .. }, Lang::En) => "Type A (t)",
        (TypeA { .. }, Lang::Tr) => "A tipi (t)",
        (TypeAPooled { .. }, Lang::En) => "Type A, pooled (t)",
        (TypeAPooled { .. }, Lang::Tr) => "A tipi, birleştirilmiş (t)",
    }
}

fn dist_info(d: &DistributionSpec, lang: Lang) -> String {
    use DistributionSpec::*;
    let n = |x: f64| fmt_given(x, lang);
    let bounds = |lower: Option<f64>, upper: Option<f64>, value: Option<f64>, half: Option<f64>| match (
        lower, upper, value, half,
    ) {
        (Some(l), Some(u), _, _) => format!("[{}; {}]", n(l), n(u)),
        (_, _, Some(v), Some(a)) => format!("{} ± {}", n(v), n(a)),
        _ => String::new(),
    };
    match d {
        Constant { value } => n(*value),
        Normal { sd: Some(s), .. } => format!("u = {}", n(*s)),
        Normal { expanded: Some(u), k: Some(k), .. } => format!("U = {}, k = {}", n(*u), n(*k)),
        Normal { .. } => String::new(),
        T { scale, expanded, k, dof, .. } => match (scale, expanded, k) {
            (Some(s), _, _) => format!("s = {}, ν = {}", n(*s), n(*dof)),
            (_, Some(u), Some(k)) => format!("U = {}, k = {}, ν = {}", n(*u), n(*k), n(*dof)),
            _ => String::new(),
        },
        Rectangular { lower, upper, value, half_width }
        | Triangular { lower, upper, value, half_width }
        | Arcsine { lower, upper, value, half_width } => bounds(*lower, *upper, *value, *half_width),
        Trapezoidal { lower, upper, value, half_width, beta } => {
            format!("{}, β = {}", bounds(*lower, *upper, *value, *half_width), n(*beta))
        }
        CurvilinearTrapezoid { lower, upper, value, half_width, d } => {
            format!("{}, d = {}", bounds(*lower, *upper, *value, *half_width), n(*d))
        }
        Exponential { mean } => format!("μ = {}", n(*mean)),
        Gamma { shape, scale } => format!("α = {}, θ = {}", n(*shape), n(*scale)),
        TypeA { observations } => format!("n = {}", observations.len()),
        TypeAPooled { pooled_sd, pooled_dof, n: count, .. } => {
            format!("s_p = {}, ν_p = {}, n = {count}", n(*pooled_sd), n(*pooled_dof))
        }
    }
}

fn rounding(spec: RoundingSpec) -> Rounding {
    match spec {
        RoundingSpec::HalfEven => Rounding::HalfEvenFirstDiscarded,
        RoundingSpec::HalfUp => Rounding::HalfUp,
        RoundingSpec::Up => Rounding::Up,
    }
}

/// The reported value and expanded uncertainty as strings, rounded per the
/// project's reporting rule.
pub fn reported_strings(p: &Project, a: &Analysis, lang: Lang) -> Option<(String, String)> {
    let g = a.gum.as_ref()?;
    let r = report_result(
        g.estimate,
        g.expanded_uncertainty,
        p.reporting.significant_digits,
        rounding(p.reporting.rounding),
        Rounding::HalfEvenFirstDiscarded,
    );
    let fix = |s: String| if lang == Lang::Tr { s.replace('.', ",") } else { s };
    Some((fix(r.value), fix(r.uncertainty)))
}

fn statement(p: &Project, a: &Analysis, lang: Lang) -> Option<String> {
    let g = a.gum.as_ref()?;
    let (v, u) = reported_strings(p, a, lang)?;
    let unit = a.model.output_unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
    let k = fmt_num(g.coverage_factor, 3, lang);
    let pct = fmt_pct(g.coverage_probability, 4, lang, true);
    Some(match lang {
        Lang::En => format!(
            "{} = ({v} ± {u}){unit}, where the expanded uncertainty is the combined standard uncertainty \
             multiplied by the coverage factor k = {k}, corresponding to a coverage probability of approximately {pct}.",
            a.model.output_name
        ),
        Lang::Tr => format!(
            "{} = ({v} ± {u}){unit}; genişletilmiş belirsizlik, birleşik standart belirsizliğin k = {k} kapsam \
             faktörüyle çarpılmasıyla elde edilmiştir ve yaklaşık {pct} kapsam olasılığına karşılık gelir.",
            a.model.output_name
        ),
    })
}

/// Markdown report.
pub fn markdown(p: &Project, a: &Analysis, lang: Lang, generated: Option<&str>) -> String {
    let l = labels(lang);
    let n = |x: f64| fmt_num(x, 6, lang);
    let n3 = |x: f64| fmt_num(x, 3, lang);
    let mut s = String::new();
    let _ = writeln!(s, "# {}\n", p.metadata.title.get(lang));
    let _ = writeln!(s, "*{}*\n", l.report);
    if let Some(d) = &p.metadata.description {
        let _ = writeln!(s, "{}\n", d.get(lang));
    }
    let _ = writeln!(s, "## {}\n", l.model);
    let unit = a.model.output_unit.clone().map(|u| format!("  [{u}]")).unwrap_or_default();
    let _ = writeln!(s, "```\n{} = {}{unit}\n```\n", a.model.output_name, p.model.output.expression);
    if !p.model.intermediates.is_empty() {
        let _ = writeln!(s, "{}:\n\n```", l.intermediates);
        for i in &p.model.intermediates {
            let _ = writeln!(s, "{} = {}", i.name, i.expression);
        }
        let _ = writeln!(s, "```\n");
    }
    let _ = writeln!(s, "## {}\n", l.inputs);
    let _ = writeln!(s, "| {} | {} | {} | {} |\n|---|---|---|---|", l.quantity, l.unit, l.distribution, l.information);
    for q in &p.model.inputs {
        let desc = q.description.as_ref().map(|d| format!(" — {}", d.get(lang))).unwrap_or_default();
        let _ = writeln!(
            s,
            "| {}{desc} | {} | {} | {} |",
            q.name,
            q.unit.clone().unwrap_or_default(),
            dist_name(&q.distribution, lang),
            dist_info(&q.distribution, lang)
        );
    }
    let _ = writeln!(s);
    if let Some(g) = &a.gum {
        let _ = writeln!(s, "## {}\n", l.budget);
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} | {} | {} |\n|---|---:|---:|---:|---:|---:|---:|",
            l.quantity, l.estimate, l.std_unc, l.dof, l.sensitivity, l.contribution, l.share
        );
        for r in &g.budget {
            let _ = writeln!(
                s,
                "| {} | {} | {} | {} | {} | {} | {} |",
                r.name,
                n(r.estimate),
                n3(r.standard_uncertainty),
                n3(r.dof),
                n3(r.sensitivity),
                n3(r.contribution),
                fmt_pct(r.variance_share, 3, lang, false)
            );
        }
        let _ = writeln!(s, "\n## {}\n", l.result);
        let unit = a.model.output_unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
        let _ = writeln!(s, "- {}: {}{unit}", l.estimate, n(g.estimate));
        let _ = writeln!(s, "- {}: {}{unit}", l.combined, n3(g.combined_standard_uncertainty));
        let _ = writeln!(s, "- {}: {}", l.eff_dof, n3(g.effective_dof));
        let _ = writeln!(s, "- {}: {}", l.k, n3(g.coverage_factor));
        let _ = writeln!(s, "- {}: {}", l.p, fmt_pct(g.coverage_probability, 4, lang, true));
        let _ = writeln!(s, "- {}: {}{unit}", l.expanded, n3(g.expanded_uncertainty));
        if let Some(st) = statement(p, a, lang) {
            let _ = writeln!(s, "\n**{}:** {st}\n", l.reported);
        }
    }
    if let Some(m) = &a.mcm {
        let _ = writeln!(s, "## {}\n", l.mcm);
        let _ = writeln!(s, "- {}: {} ({}: {})", l.trials, m.trials, l.seed, m.seed);
        if !m.converged {
            let _ = writeln!(s, "- ⚠ {}", l.not_converged);
        }
        let _ = writeln!(s, "- {}: {}", l.mcm_estimate, n(m.estimate));
        let _ = writeln!(s, "- {}: {}", l.mcm_u, n3(m.standard_uncertainty));
        let (sl, sh) = m.shortest_interval;
        let (yl, yh) = m.symmetric_interval;
        let pct = fmt_pct(m.coverage_probability, 4, lang, true);
        let _ = writeln!(s, "- {} ({pct}): [{}; {}]", l.shortest, n(sl), n(sh));
        let _ = writeln!(s, "- {} ({pct}): [{}; {}]", l.symmetric, n(yl), n(yh));
        if let Some(v) = &a.validation {
            let verdict = if v.validated { l.validated } else { l.not_validated };
            let _ = writeln!(
                s,
                "\n**{}:** {verdict} (n_dig = {}, {} δ = {}; d_low = {}, d_high = {}).\n",
                l.validation,
                v.ndig,
                l.tolerance,
                n3(v.tolerance),
                n3(v.d_low),
                n3(v.d_high)
            );
        } else {
            let _ = writeln!(s);
        }
    }
    let warnings: Vec<&String> = a.gum.iter().flat_map(|g| g.warnings.iter()).collect();
    if !warnings.is_empty() {
        let _ = writeln!(s, "## {}\n", l.warnings);
        for w in warnings {
            let _ = writeln!(s, "- {w}");
        }
        let _ = writeln!(s);
    }
    if !p.metadata.explanation.is_empty() {
        let _ = writeln!(s, "## {}\n", l.explanation);
        for (i, e) in p.metadata.explanation.iter().enumerate() {
            let _ = writeln!(s, "{}. {}", i + 1, e.get(lang));
        }
        let _ = writeln!(s);
    }
    if !p.metadata.notes.is_empty() {
        let _ = writeln!(s, "## {}\n", l.notes);
        for e in &p.metadata.notes {
            let _ = writeln!(s, "- {}", e.get(lang));
        }
        let _ = writeln!(s);
    }
    let checks = check(p, a);
    if !checks.is_empty() {
        let _ = writeln!(s, "## {}\n", l.checks);
        if let Some(r) = p.expected.as_ref().and_then(|e| e.reference.as_ref()) {
            let _ = writeln!(s, "{r}\n");
        }
        let _ = writeln!(s, "| | {} | {} | ± | |\n|---|---:|---:|---:|---|", l.computed, l.expected);
        for c in &checks {
            let _ = writeln!(
                s,
                "| {} | {} | {} | {} | {} |",
                c.what,
                n(c.computed),
                n(c.expected),
                n3(c.tolerance),
                if c.passed { l.passed } else { l.failed }
            );
        }
        let _ = writeln!(s);
    }
    let _ = writeln!(s, "## {}\n", l.sources);
    for src in &p.metadata.sources {
        let sec = src.section.as_ref().map(|x| format!(", {x}")).unwrap_or_default();
        let url = src.url.as_ref().map(|x| format!(" <{x}>")).unwrap_or_default();
        let _ = writeln!(s, "- {}{sec}{url}", src.document);
    }
    let _ = writeln!(s, "\n**{}:** JCGM 100:2008 (GUM); JCGM 101:2008 (GUM-S1).\n", l.methods);
    let _ = writeln!(s, "---\n");
    let gen = generated.map(|g| format!(", {g}")).unwrap_or_default();
    let _ = writeln!(s, "{} {SOFTWARE_NAME} {SOFTWARE_VERSION}{gen}.  ", l.generated_by);
    let _ = writeln!(s, "{}: {CITATION}", l.cite);
    s
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

/// Horizontal bar chart of variance shares (SVG).
fn contributions_svg(a: &Analysis, lang: Lang) -> Option<String> {
    let g = a.gum.as_ref()?;
    let mut rows: Vec<(&str, f64)> =
        g.budget.iter().filter(|r| r.variance_share > 0.0).map(|r| (r.name.as_str(), r.variance_share)).collect();
    if rows.is_empty() {
        return None;
    }
    rows.sort_by(|x, y| y.1.total_cmp(&x.1));
    let (w, row_h, left) = (640.0, 26.0, 150.0);
    let h = row_h * rows.len() as f64 + 20.0;
    let max = rows[0].1.max(1e-300);
    let mut s = format!(
        r#"<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="{}" xmlns="http://www.w3.org/2000/svg">"#,
        esc(labels(lang).contributions_chart)
    );
    for (i, (name, share)) in rows.iter().enumerate() {
        let y = 10.0 + i as f64 * row_h;
        let bw = (w - left - 70.0) * share / max;
        let _ = write!(
            s,
            r#"<text x="{}" y="{}" text-anchor="end" class="lbl">{}</text><rect x="{left}" y="{}" width="{bw:.1}" height="{}" class="bar"/><text x="{:.1}" y="{}" class="val">{}</text>"#,
            left - 8.0,
            y + row_h * 0.62,
            esc(name),
            y + 3.0,
            row_h - 8.0,
            left + bw + 6.0,
            y + row_h * 0.62,
            fmt_pct(*share, 3, lang, false)
        );
    }
    s.push_str("</svg>");
    Some(s)
}

/// MCM histogram with the GUM PDF overlaid and both coverage intervals (SVG).
fn histogram_svg(a: &Analysis, lang: Lang) -> Option<String> {
    let m = a.mcm.as_ref()?;
    let hist = &m.histogram;
    let total = m.trials as f64;
    let nb = hist.counts.len();
    if nb == 0 || hist.bin_width <= 0.0 {
        return None;
    }
    let x0 = hist.lower;
    let x1 = hist.lower + hist.bin_width * nb as f64;
    let dens: Vec<f64> = hist.counts.iter().map(|&c| c as f64 / (total * hist.bin_width)).collect();
    let gum_pdf = |x: f64| -> f64 {
        a.gum.as_ref().map_or(0.0, |g| {
            let u = g.combined_standard_uncertainty;
            if u <= 0.0 {
                return 0.0;
            }
            let z = (x - g.estimate) / u;
            if g.effective_dof.is_finite() {
                student_t_pdf(z, g.effective_dof) / u
            } else {
                normal_pdf(z) / u
            }
        })
    };
    let ymax = dens
        .iter()
        .cloned()
        .fold(0.0, f64::max)
        .max((0..=200).map(|i| gum_pdf(x0 + (x1 - x0) * i as f64 / 200.0)).fold(0.0, f64::max));
    if ymax.is_nan() || ymax <= 0.0 {
        return None;
    }
    let (w, h, pad, top) = (640.0, 330.0, 30.0, 72.0);
    let sx = |x: f64| pad + (x - x0) / (x1 - x0) * (w - 2.0 * pad);
    let sy = |y: f64| h - pad - y / ymax * (h - pad - top);
    let l = labels(lang);
    let mut s = format!(
        r#"<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="{}" xmlns="http://www.w3.org/2000/svg">"#,
        esc(l.histogram_chart)
    );
    for (i, d) in dens.iter().enumerate() {
        let xa = sx(x0 + i as f64 * hist.bin_width);
        let xb = sx(x0 + (i + 1) as f64 * hist.bin_width);
        let _ = write!(
            s,
            r#"<rect x="{xa:.2}" y="{:.2}" width="{:.2}" height="{:.2}" class="hist"/>"#,
            sy(*d),
            (xb - xa).max(0.5),
            sy(0.0) - sy(*d)
        );
    }
    if a.gum.is_some() {
        let pts: Vec<String> = (0..=200)
            .map(|i| {
                let x = x0 + (x1 - x0) * i as f64 / 200.0;
                format!("{:.2},{:.2}", sx(x), sy(gum_pdf(x)))
            })
            .collect();
        let _ = write!(s, r#"<polyline points="{}" class="pdf"/>"#, pts.join(" "));
    }
    let (lo, hi) = m.interval(a.interval_kind);
    for x in [lo, hi] {
        if x >= x0 && x <= x1 {
            let _ = write!(s, r#"<line x1="{0:.2}" x2="{0:.2}" y1="{1}" y2="{2}" class="mcm"/>"#, sx(x), top, h - pad);
        }
    }
    if let Some(g) = &a.gum {
        for x in [g.interval.0, g.interval.1] {
            if x >= x0 && x <= x1 {
                let _ = write!(
                    s,
                    r#"<line x1="{0:.2}" x2="{0:.2}" y1="{1}" y2="{2}" class="gumline"/>"#,
                    sx(x),
                    top,
                    h - pad
                );
            }
        }
    }
    let _ = write!(
        s,
        r#"<line x1="{pad}" x2="{xr}" y1="{yb}" y2="{yb}" class="axis"/><text x="{pad}" y="{yt}" class="lbl">{lo}</text><text x="{xr}" y="{yt}" text-anchor="end" class="lbl">{hi}</text>"#,
        xr = w - pad,
        yb = h - pad,
        yt = h - 8.0,
        lo = esc(&fmt_num(x0, 5, lang)),
        hi = esc(&fmt_num(x1, 5, lang))
    );
    let kind = match a.interval_kind {
        IntervalKind::Shortest => l.shortest,
        IntervalKind::Symmetric => l.symmetric,
    };
    let _ = write!(
        s,
        r#"<g class="legend"><rect x="{}" y="10" width="12" height="12" class="hist"/><text x="{}" y="20" class="lbl">MCM</text><line x1="{}" x2="{}" y1="34" y2="34" class="pdf"/><text x="{}" y="38" class="lbl">{}</text><line x1="{}" x2="{}" y1="52" y2="52" class="mcm"/><text x="{}" y="56" class="lbl">{}</text></g>"#,
        w - 230.0,
        w - 212.0,
        w - 230.0,
        w - 218.0,
        w - 212.0,
        l.gum_pdf,
        w - 230.0,
        w - 218.0,
        w - 212.0,
        esc(kind)
    );
    s.push_str("</svg>");
    Some(s)
}

/// Converts the Markdown subset produced by [`markdown`] to HTML.
fn md_to_html(md: &str) -> String {
    let mut html = String::new();
    let mut in_code = false;
    let mut in_table = false;
    let mut in_list: Option<&str> = None;
    let close_list = |html: &mut String, in_list: &mut Option<&str>| {
        if let Some(tag) = in_list.take() {
            let _ = writeln!(html, "</{tag}>");
        }
    };
    let inline = |t: &str| -> String {
        let mut out = String::new();
        let mut bold = false;
        let mut italic = false;
        let escaped = esc(t);
        let mut chars = escaped.chars().peekable();
        while let Some(c) = chars.next() {
            if c == '*' && chars.peek() == Some(&'*') {
                chars.next();
                out.push_str(if bold { "</strong>" } else { "<strong>" });
                bold = !bold;
            } else if c == '*' {
                out.push_str(if italic { "</em>" } else { "<em>" });
                italic = !italic;
            } else {
                out.push(c);
            }
        }
        out
    };
    for line in md.lines() {
        if line.starts_with("```") {
            close_list(&mut html, &mut in_list);
            html.push_str(if in_code { "</pre>\n" } else { "<pre>" });
            in_code = !in_code;
            continue;
        }
        if in_code {
            let _ = writeln!(html, "{}", esc(line));
            continue;
        }
        if line.starts_with('|') {
            close_list(&mut html, &mut in_list);
            let cells: Vec<&str> = line.trim_matches('|').split('|').map(str::trim).collect();
            if cells.iter().all(|c| c.chars().all(|ch| ch == '-' || ch == ':')) {
                continue;
            }
            if !in_table {
                html.push_str("<table><thead><tr>");
                for c in &cells {
                    let _ = write!(html, "<th>{}</th>", inline(c));
                }
                html.push_str("</tr></thead><tbody>\n");
                in_table = true;
            } else {
                html.push_str("<tr>");
                for c in &cells {
                    let _ = write!(html, "<td>{}</td>", inline(c));
                }
                html.push_str("</tr>\n");
            }
            continue;
        } else if in_table {
            html.push_str("</tbody></table>\n");
            in_table = false;
        }
        if let Some(rest) = line.strip_prefix("## ") {
            close_list(&mut html, &mut in_list);
            let _ = writeln!(html, "<h2>{}</h2>", inline(rest));
        } else if let Some(rest) = line.strip_prefix("# ") {
            close_list(&mut html, &mut in_list);
            let _ = writeln!(html, "<h1>{}</h1>", inline(rest));
        } else if let Some(rest) = line.strip_prefix("- ") {
            if in_list != Some("ul") {
                close_list(&mut html, &mut in_list);
                html.push_str("<ul>\n");
                in_list = Some("ul");
            }
            let _ = writeln!(html, "<li>{}</li>", inline(rest));
        } else if line.split_once(". ").is_some_and(|(n, _)| !n.is_empty() && n.chars().all(|c| c.is_ascii_digit())) {
            if in_list != Some("ol") {
                close_list(&mut html, &mut in_list);
                html.push_str("<ol>\n");
                in_list = Some("ol");
            }
            let (_, rest) = line.split_once(". ").unwrap();
            let _ = writeln!(html, "<li>{}</li>", inline(rest));
        } else if line == "---" {
            close_list(&mut html, &mut in_list);
            html.push_str("<hr>\n");
        } else if line.trim().is_empty() {
            close_list(&mut html, &mut in_list);
        } else {
            close_list(&mut html, &mut in_list);
            let _ = writeln!(html, "<p>{}</p>", inline(line.trim_end()));
        }
    }
    close_list(&mut html, &mut in_list);
    if in_table {
        html.push_str("</tbody></table>\n");
    }
    html
}

