        let unit = a.model.output_unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
        let _ =
            writeln!(s, "- {}: {}{unit}", l.estimate, fmt_estimate(g.estimate, g.combined_standard_uncertainty, lang));
