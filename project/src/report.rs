fn dist_info(d: &DistributionSpec, lang: Lang) -> String {
    use DistributionSpec::*;
    let n = |x: f64| fmt_given(x, lang);
    let bounds = |lower: Option<f64>, upper: Option<f64>, value: Option<f64>, half: Option<f64>| match (
        lower, upper, value, half,
    ) {
        (Some(l), Some(u), _, _) => format!("[{}; {}]", n(l), n(u)),
        (_, _, Some(v), Some(a)) => format!("{} ± {}", n(v), n(a)),
        _ => String::new(),
    };
    match d {
        Constant { value } => n(*value),
        Normal { sd: Some(s), .. } => format!("u = {}", n(*s)),
        Normal { expanded: Some(u), k: Some(k), .. } => format!("U = {}, k = {}", n(*u), n(*k)),
        Normal { .. } => String::new(),
        T { scale, expanded, k, dof, .. } => match (scale, expanded, k) {
            (Some(s), _, _) => format!("s = {}, ν = {}", n(*s), n(*dof)),
            (_, Some(u), Some(k)) => format!("U = {}, k = {}, ν = {}", n(*u), n(*k), n(*dof)),
            _ => String::new(),
        },
        Rectangular { lower, upper, value, half_width }
        | Triangular { lower, upper, value, half_width }
        | Arcsine { lower, upper, value, half_width } => bounds(*lower, *upper, *value, *half_width),
        Trapezoidal { lower, upper, value, half_width, beta } => {
            format!("{}, β = {}", bounds(*lower, *upper, *value, *half_width), n(*beta))
        }
        CurvilinearTrapezoid { lower, upper, value, half_width, d } => {
            format!("{}, d = {}", bounds(*lower, *upper, *value, *half_width), n(*d))
        }
        Exponential { mean } => format!("μ = {}", n(*mean)),
        Gamma { shape, scale } => format!("α = {}, θ = {}", n(*shape), n(*scale)),
        TypeA { observations } => format!("n = {}", observations.len()),
        TypeAPooled { pooled_sd, pooled_dof, n: count, .. } => {
            format!("s_p = {}, ν_p = {}, n = {count}", n(*pooled_sd), n(*pooled_dof))
        }
    }
}

fn rounding(spec: RoundingSpec) -> Rounding {
    match spec {
        RoundingSpec::HalfEven => Rounding::HalfEvenFirstDiscarded,
        RoundingSpec::HalfUp => Rounding::HalfUp,
        RoundingSpec::Up => Rounding::Up,
    }
}

/// A value and its expanded uncertainty rounded for reporting: U to the
/// stated number of significant digits (or decimal places) by the stated
/// rule, the value to the same decimal place (half to even).
pub fn round_reported(value: f64, expanded: f64, spec: &ReportingSpec, lang: Lang) -> (String, String) {
    let rule = rounding(spec.rounding);
    let (v, u) = match spec.decimal_places {
        Some(d) => (format_at_place(value, -d, Rounding::HalfEvenFirstDiscarded), format_at_place(expanded, -d, rule)),
        None => {
            let r = report_result(value, expanded, spec.significant_digits, rule, Rounding::HalfEvenFirstDiscarded);
            (r.value, r.uncertainty)
        }
    };
    let fix = |s: String| if lang == Lang::Tr { s.replace('.', ",") } else { s };
    (fix(v), fix(u))
}

/// The reported value and expanded uncertainty of a model project as
/// strings, rounded per the project's reporting rule.
pub fn reported_strings(p: &Project, a: &Analysis, lang: Lang) -> Option<(String, String)> {
    let g = a.gum.as_ref()?;
    let (u, _) = crate::reported_expanded(p, g.estimate, g.expanded_uncertainty);
    Some(round_reported(g.estimate, u, &p.reporting, lang))
}

fn statement(p: &Project, a: &Analysis, lang: Lang) -> Option<String> {
    let g = a.gum.as_ref()?;
    let (v, u) = reported_strings(p, a, lang)?;
    let unit = a.model.output_unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
    let k = fmt_num(g.coverage_factor, 3, lang);
    let pct = fmt_pct(g.coverage_probability, 4, lang, true);
    let (_, raised) = crate::reported_expanded(p, g.estimate, g.expanded_uncertainty);
    let evaluated = fmt_num(g.expanded_uncertainty, 2, lang);
    let mut text = match lang {
        Lang::En => format!(
            "{} = ({v} ± {u}){unit}, where the expanded uncertainty is the combined standard uncertainty \
             multiplied by the coverage factor k = {k}, corresponding to a coverage probability of approximately {pct}.",
            a.model.output_name
        ),
        Lang::Tr => format!(
            "{} = ({v} ± {u}){unit}; genişletilmiş belirsizlik, birleşik standart belirsizliğin k = {k} kapsam \
             faktörüyle çarpılmasıyla elde edilmiştir ve yaklaşık {pct} kapsam olasılığına karşılık gelir.",
            a.model.output_name
        ),
    };
    if raised {
        text += &match lang {
            Lang::En => format!(
                " The evaluated expanded uncertainty, {evaluated}{unit}, is smaller than the laboratory's calibration and \
                 measurement capability, so the CMC is reported (ILAC P14:09/2020, 5.5)."
            ),
            Lang::Tr => format!(
                " Değerlendirilen genişletilmiş belirsizlik, {evaluated}{unit}, laboratuvarın kalibrasyon ve ölçüm \
                 yeteneğinden (CMC) küçük olduğundan CMC raporlanmıştır (ILAC P14:09/2020, 5.5)."
            ),
        };
    }
    if p.reporting.significant_digits > 2 {
        text += match lang {
            Lang::En => " Note: ILAC P14:09/2020, 5.3, allows at most two significant digits for the expanded uncertainty on calibration certificates.",
            Lang::Tr => " Not: ILAC P14:09/2020, 5.3, kalibrasyon sertifikalarında genişletilmiş belirsizlik için en çok iki anlamlı basamağa izin verir.",
        };
    }
    Some(text)
}

/// The result with an uncorrected bias (Magnusson & Ellison 2008, Table 3).
fn bias_statement(p: &Project, a: &Analysis, lang: Lang) -> Option<String> {
    let g = a.gum.as_ref()?;
    let b = p.reporting.uncorrected_bias.as_ref()?;
    let (strategy, lo, hi) = crate::uncorrected_bias_interval(p, a)?;
    let unit = a.model.output_unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
    let (v, big) = round_reported(g.estimate, lo.max(hi), &p.reporting, lang);
    let interval = if (lo - hi).abs() <= 1e-12 * hi.abs().max(1e-300) {
        format!("({v} ± {big}){unit}")
    } else {
        // Both half-widths at the decimal place of the larger one.
        let places = big.rsplit([',', '.']).next().filter(|_| big.contains(['.', ','])).map_or(0, str::len);
        let f = |x: f64| {
            let t = format!("{x:.places$}");
            if lang == Lang::Tr {
                t.replace('.', ",")
            } else {
                t
            }
        };
        format!("{v}{unit} (−{}, +{})", f(lo), f(hi))
    };
    let (bv, bu) = (fmt_num(b.bias, 3, lang), fmt_num(b.u_bias, 2, lang));
    let name = &a.model.output_name;
    let k = fmt_num(g.coverage_factor, 3, lang);
    let s = strategy.label();
    Some(match lang {
        Lang::En => format!(
            "{name} = {interval}, not corrected for the estimated bias b = {bv}{unit} (u(b) = {bu}{unit}); the interval \
             includes the bias by the {s} approach of Magnusson & Ellison (2008), k = {k}."
        ),
        Lang::Tr => format!(
            "{name} = {interval}; tahmin edilen sapma b = {bv}{unit} (u(b) = {bu}{unit}) için düzeltme yapılmamıştır; \
             aralık sapmayı Magnusson ve Ellison'un (2008) {s} yaklaşımıyla içerir, k = {k}."
        ),
    })
}

fn model_statements(p: &Project, a: &Analysis, lang: Lang) -> Vec<String> {
    statement(p, a, lang)
        .into_iter()
        .chain(bias_statement(p, a, lang))
        .chain(a.conformity.iter().flat_map(|c| conformity::statements(c, lang)))
        .collect()
}

