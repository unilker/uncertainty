/// Self-contained HTML report with charts.
pub fn html(p: &Project, e: &Evaluation, lang: Lang, generated: Option<&str>) -> String {
    let l = labels(lang);
    let body = md_to_html(&markdown(p, e, lang, generated));
    let mut figures = String::new();
    let mut anchor = format!("<h2>{}</h2>", esc(l.mcm));
    match e {
        Evaluation::Model(a) => {
            let rows: Vec<(&str, f64)> =
                a.gum.iter().flat_map(|g| g.budget.iter().map(|r| (r.name.as_str(), r.variance_share))).collect();
            if let Some(svg) = contributions_svg(&rows, lang) {
                let _ =
                    write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(l.contributions_chart));
            }
            if let Some(svg) = histogram_svg(a, lang) {
                let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(l.histogram_chart));
            }
            if let Some(svg) = a.conformity.as_ref().and_then(|c| conformity::chart_svg(c, lang)) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(conformity::cf_labels(lang).chart)
                );
            }
        }
        Evaluation::TopDown(t) => {
            let unit = p.topdown.as_ref().and_then(|s| s.unit.clone()).map(|u| format!(" {u}")).unwrap_or_default();
            for lv in t.levels.iter().take(4) {
                let rows: Vec<(&str, f64)> = lv.shares.iter().map(|&(i, sh)| (t.budget[i].name.as_str(), sh)).collect();
                let caption = match lv.level {
                    Some(x) => format!("{} — {}{unit}", l.contributions_chart, fmt_given(x, lang)),
                    None => l.contributions_chart.to_string(),
                };
                if let Some(svg) = contributions_svg(&rows, lang) {
                    let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(&caption));
                }
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::Proficiency(a) => {
            if let Some(svg) = p.proficiency.as_ref().and_then(|spec| proficiency::homogeneity_svg(spec, a, lang)) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(proficiency::pt_labels(lang).homogeneity_chart)
                );
            }
            if let Some(svg) = proficiency::z_scores_svg(a, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(proficiency::pt_labels(lang).chart)
                );
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::Calibration(a) => {
            if let Some(svg) = calibration::deviations_svg(p, a, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(calibration::cal_labels(lang).chart)
                );
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::Conformity(a) => {
            if let Some(svg) = conformity::chart_svg(a, lang) {
                let d = conformity::cf_labels(lang);
                let caption = if a.results.is_empty() { d.limits_chart } else { d.chart };
                let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(caption));
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::Interlab(a) => {
            let d = interlab::il_labels(lang);
            for (is_h, caption) in [(true, d.h_chart), (false, d.k_chart)] {
                if let Some(svg) = interlab::mandel_svg(a, is_h, lang) {
                    let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(caption));
                }
            }
            if !a.relationships.is_empty() {
                if let Some(svg) = interlab::precision_svg(a, lang) {
                    let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(d.s_chart));
                }
            }
            let excluded = p.precision_experiment.as_ref().is_some_and(|s| !s.exclude.is_empty());
            anchor = format!("<h2>{}</h2>", esc(if excluded { d.exclusions } else { d.precision }));
        }
        Evaluation::Multivariate(a) => {
            if let Some(svg) = multivariate::regions_svg(a, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(multivariate::mv_labels(lang).chart)
                );
            } else if let Some(svg) = multivariate::uncertainties_svg(a, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(multivariate::mv_labels(lang).u_chart)
                );
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::ControlChart(a) => {
            let d = qc::qc_labels(lang);
            if let Some(svg) = qc::chart_svg(a, lang) {
                let caption = if a.values.is_empty() { d.limits_caption } else { d.chart_caption };
                let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(caption));
            }
            anchor = format!("<h2>{}</h2>", esc(if a.values.is_empty() { l.explanation } else { d.daily }));
        }
        Evaluation::ErrorFunction(a) => {
            if let Some(svg) = weighing::chart_svg(a, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(weighing::ef_labels(lang).chart)
                );
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::Multicomponent(a) => {
            let rows: Vec<(&str, f64)> = a.results.iter().map(|(n, _, r)| (n.as_str(), r.risk)).collect();
            if let Some(svg) = contributions_svg(&rows, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(multiconformity::mc_labels(lang).results)
                );
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
        Evaluation::Sampling(a) => {
            if let Some(svg) = sampling::chart_svg(a, lang) {
                let _ = write!(
                    figures,
                    "<figure><figcaption>{}</figcaption>{svg}</figure>",
                    esc(sampling::sp_labels(lang).chart)
                );
            }
            anchor = format!("<h2>{}</h2>", esc(l.explanation));
        }
    }
    // Place the figures before the Monte Carlo section (top-down: before the
    // explanation), or else before the sources.
    let body = if let Some(i) = body.find(&anchor).or_else(|| body.find(&format!("<h2>{}</h2>", esc(l.notes)))) {
        format!("{}{figures}{}", &body[..i], &body[i..])
    } else if let Some(i) = body.find(&format!("<h2>{}</h2>", esc(l.sources))) {
        format!("{}{figures}{}", &body[..i], &body[i..])
    } else {
        format!("{body}{figures}")
    };
    page(p.metadata.title.get(lang), &body, lang)
}

/// A self-contained HTML page with the report style.
fn page(title: &str, body: &str, lang: Lang) -> String {
    let html_lang = match lang {
        Lang::En => "en",
        Lang::Tr => "tr",
    };
    format!(
        "<!doctype html>\n<html lang=\"{html_lang}\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>{}</title><style>{CSS}</style></head><body><main>\n{body}</main></body></html>\n",
        esc(title)
    )
}

