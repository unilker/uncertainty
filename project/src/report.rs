/// Formats a number with `sig` significant digits, switching to ×10ⁿ
/// notation for very small or large magnitudes; Turkish uses a decimal comma.
pub fn fmt_num(x: f64, sig: usize, lang: Lang) -> String {
    let s = if !x.is_finite() {
        if x.is_nan() {
            "—".to_string()
        } else {
            "∞".to_string()
        }
    } else if x == 0.0 {
        "0".to_string()
    } else {
        let mut e = x.abs().log10().floor() as i32;
        // Rounding may carry into the next decade (9.999 → 10.0).
        let scale = 10f64.powi(sig as i32 - 1 - e);
        if (x.abs() * scale).round() >= 10f64.powi(sig as i32) {
            e += 1;
        }
        if (-4..10).contains(&e) {
            let decimals = (sig as i32 - 1 - e).max(0) as usize;
            format!("{x:.decimals$}")
        } else {
            let m = x / 10f64.powi(e);
            format!("{m:.prec$} × 10{}", superscript(e), prec = sig.saturating_sub(1))
        }
    };
    match lang {
        Lang::Tr => s.replace('.', ","),
        Lang::En => s,
    }
}

fn superscript(e: i32) -> String {
    e.to_string()
        .chars()
        .map(|c| match c {
            '-' => '⁻',
            '0' => '⁰',
            '1' => '¹',
            '2' => '²',
            '3' => '³',
            '4' => '⁴',
            '5' => '⁵',
            '6' => '⁶',
            '7' => '⁷',
            '8' => '⁸',
            '9' => '⁹',
            other => other,
        })
        .collect()
}

/// An estimate with enough significant digits to show two digits of its
/// standard uncertainty (at least six).
pub fn fmt_estimate(x: f64, u: f64, lang: Lang) -> String {
    let sig = if x != 0.0 && u > 0.0 && x.is_finite() && u.is_finite() {
        (x.abs().log10().floor() - u.log10().floor() + 2.0).clamp(6.0, 15.0) as usize
    } else {
        6
    };
    fmt_num(x, sig, lang)
}

/// Formats an input value as given (shortest round-trip representation).
fn fmt_given(x: f64, lang: Lang) -> String {
    let s = if x != 0.0 && !(1e-6..1e9).contains(&x.abs()) {
        let t = format!("{x:e}");
        match t.split_once('e') {
            Some((m, e)) => format!("{m} × 10{}", superscript(e.parse().unwrap_or(0))),
            None => t,
        }
    } else {
        format!("{x}")
    };
    match lang {
        Lang::Tr => s.replace('.', ","),
        Lang::En => s,
    }
}

/// A percentage: "95.45 %" in English, "%95,45" in Turkish (TS 1212 usage).
fn fmt_pct(fraction: f64, sig: usize, lang: Lang, trim: bool) -> String {
    let mut v = fmt_num(100.0 * fraction, sig, lang);
    if trim && v.contains(['.', ',']) && !v.contains('×') {
        v = v.trim_end_matches('0').trim_end_matches(['.', ',']).to_string();
    }
    match lang {
        Lang::En => format!("{v} %"),
        Lang::Tr => format!("%{v}"),
    }
}

