fn range_text(r: &LevelRange, lang: Lang) -> String {
    let n = |x: f64| fmt_given(x, lang);
    match (r.min, r.max) {
        (None, None) => td_labels(lang).all.to_string(),
        (Some(a), None) => format!("≥ {}", n(a)),
        (None, Some(b)) => format!("< {}", n(b)),
        (Some(a), Some(b)) => format!("[{}; {})", n(a), n(b)),
    }
}

/// The reported result(s) in words: one statement for a model project
/// (GUM), one per level for a top-down project.
pub fn reported_statements(p: &Project, e: &Evaluation, lang: Lang) -> Vec<String> {
    match e {
        Evaluation::Model(a) => model_statements(p, a, lang),
        Evaluation::TopDown(t) => topdown_statements(p, t, lang),
        Evaluation::Proficiency(a) => proficiency::statements(p, a, lang),
        Evaluation::Calibration(a) => calibration::statements(p, a, lang),
        Evaluation::Conformity(a) => conformity::statements(a, lang),
        Evaluation::Interlab(a) => interlab::statements(a, lang),
        Evaluation::Multivariate(a) => multivariate::statements(a, lang),
        Evaluation::ControlChart(a) => qc::statements(a, lang),
        Evaluation::Sampling(a) => sampling::statements(a, lang),
        Evaluation::ErrorFunction(a) => weighing::statements(a, lang),
        Evaluation::Multicomponent(a) => multiconformity::statements(a, lang),
    }
}

/// The reported result at each level of a top-down evaluation.
fn topdown_statements(p: &Project, t: &TopDownAnalysis, lang: Lang) -> Vec<String> {
    let Some(spec) = p.topdown.as_ref() else { return Vec::new() };
    let unit = spec.unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
    let k = fmt_num(t.coverage_factor, 3, lang);
    t.levels
        .iter()
        .map(|lv| match (lv.value, lv.expanded_uncertainty) {
            (Some(v), Some(big)) => {
                let (vs, us) = round_reported(v, big, &p.reporting, lang);
                format!("{} = ({vs} ± {us}){unit} (k = {k})", spec.quantity)
            }
            _ => {
                let (_, us) = round_reported(0.0, 100.0 * lv.relative_expanded, &p.reporting, lang);
                let pct = match lang {
                    Lang::En => format!("{us} %"),
                    Lang::Tr => format!("%{us}"),
                };
                format!("U = {pct} (k = {k}), {}", td_labels(lang).relative_statement)
            }
        })
        .collect()
}

/// s(c) of a level-dependent precision model, e.g. "0.0233 + 0.0128·c".
fn model_text(m: &LevelModel, lang: Lang) -> String {
    let n = |x: f64| fmt_num(x, 4, lang);
    match *m {
        LevelModel::Linear { intercept, slope, dilution_factor, .. } if dilution_factor != 1.0 => {
            format!(
                "{}·({} + {}·c/{})",
                fmt_given(dilution_factor, lang),
                n(intercept),
                n(slope),
                fmt_given(dilution_factor, lang)
            )
        }
        LevelModel::Linear { intercept, slope, .. } => format!("{} + {}·c", n(intercept), n(slope)),
        LevelModel::Continuous { sd0, rsd1 } => format!("√({}² + (c·{})²)", n(sd0), fmt_pct(rsd1, 4, lang, false)),
    }
}

fn topdown_markdown(
    p: &Project,
    t: &TopDownAnalysis,
    checks: &[CheckOutcome],
    lang: Lang,
    generated: Option<&str>,
) -> String {
    let l = labels(lang);
    let d = td_labels(lang);
    let Some(spec) = p.topdown.as_ref() else { return String::new() };
    let unit = spec.unit.clone().map(|u| format!(" {u}")).unwrap_or_default();
    let n3 = |x: f64| fmt_num(x, 3, lang);
    let u_of =
        |u: f64, rel: bool| if rel { fmt_pct(u, 3, lang, false) } else { format!("{}{unit}", fmt_num(u, 3, lang)) };
    let dof = |v: f64| if v.is_finite() { fmt_given(v, lang) } else { "∞".to_string() };
    let mut s = String::new();
    let _ = writeln!(s, "# {}\n", p.metadata.title.get(lang));
    let _ = writeln!(s, "*{}*\n", l.report);
    if let Some(x) = &p.metadata.description {
        let _ = writeln!(s, "{}\n", x.get(lang));
    }
    let _ = writeln!(s, "## {}\n", d.title);
    let _ = writeln!(
        s,
        "{}: {}{}\n",
        d.measurand,
        spec.quantity,
        spec.unit.clone().map(|u| format!(" [{u}]")).unwrap_or_default()
    );

    if !t.precision.is_empty() {
        let _ = writeln!(s, "## {}\n", d.precision);
        let _ = writeln!(
            s,
            "| {} | {} | n | {} | {} | {} | {} | {} |\n|---|---|---:|---:|---:|---:|---|---:|",
            d.component, d.method, d.mean, d.sd, l.dof, d.range, d.in_budget
        );
        for (pr, ps) in t.precision.iter().zip(&spec.precision) {
            let mut method = match pr.method {
                PrecisionMethod::Series => d.m_series,
                PrecisionMethod::Groups => d.m_groups,
                PrecisionMethod::DuplicatesPooled => d.m_dup,
                PrecisionMethod::DuplicatesNormalised => d.m_dup_norm,
                PrecisionMethod::DuplicatesRange => d.m_dup_range,
                PrecisionMethod::ControlLimits => d.m_limits,
                PrecisionMethod::Given => d.m_given,
                PrecisionMethod::Linear => d.m_linear,
                PrecisionMethod::Continuous => d.m_continuous,
                PrecisionMethod::Reproducibility => d.m_reproducibility,
                PrecisionMethod::StaggeredNested => d.m_nested,
            }
            .to_string();
            if let Some((r, i, big)) = pr.nested {
                let v = |x: f64| if pr.relative { fmt_pct(x, 3, lang, false) } else { fmt_num(x, 3, lang) };
                let _ = write!(method, "; s_r = {}, s_I(T) = {}, s_R = {}", v(r), v(i), v(big));
            }
            if let Some(r) = &pr.reproducibility {
                let v = |x: f64| if pr.relative { fmt_pct(x, 3, lang, false) } else { fmt_num(x, 3, lang) };
                let _ = write!(
                    method,
                    "; s_R = {}, s_L = {}, s_r = {}",
                    v(r.s_reproducibility),
                    v(r.s_between_labs),
                    v(r.s_repeatability)
                );
                if r.lab_repeatability_used {
                    let _ = write!(method, ", s_l = {}", v(r.s_repeatability_used));
                }
                if r.replicates > 1 {
                    let _ = write!(method, ", n_r = {}", r.replicates);
                }
                let _ = write!(method, "; s′_R = {}", v(r.s_adjusted));
                if let Some(u) = r.u_method_bias {
                    let _ = write!(method, "; u(δ̂) = {}", v(u));
                }
                if let Some((delta, sd, ok)) = r.bias_check {
                    let _ = write!(
                        method,
                        "; |Δ_l| = {} {} 2s_D = {}: {}",
                        v(delta),
                        if ok { "<" } else { "≥" },
                        v(2.0 * sd),
                        if ok { d.bias_ok } else { d.bias_not_ok }
                    );
                }
            }
            if let Some(m) = &ps.mean_of {
                let _ = write!(
                    method,
                    "; {}",
                    d.mean_of.replace("{p}", &m.days.to_string()).replace("{n}", &m.replicates.to_string())
                );
            }
            if let Some(at) = &ps.to_relative_at {
                let v = match at {
                    At::Value(v) => fmt_given(*v, lang),
                    At::Keyword(_) => pr.mean.map(|m| fmt_num(m, 4, lang)).unwrap_or_default(),
                };
                let _ = write!(method, "; {}", d.rel_at.replace("{v}", &v));
            }
            if let Some(LevelModel::Linear { correlation: Some(r), .. }) = pr.model {
                let _ = write!(method, "; r = {}", fmt_num(r, 4, lang));
            }
            if let Some(v) = ps.to_absolute_at {
                let _ = write!(method, "; {}", d.abs_at.replace("{v}", &fmt_given(v, lang)));
            }
            let _ = writeln!(
                s,
                "| {} | {method} | {} | {} | {} | {} | {} | {} |",
                pr.name,
                if pr.n > 0 { pr.n.to_string() } else { "—".into() },
                pr.mean.map(|m| fmt_num(m, 4, lang)).unwrap_or_else(|| "—".into()),
                pr.model.map(|m| model_text(&m, lang)).unwrap_or_else(|| u_of(pr.raw_sd, pr.raw_relative)),
                dof(pr.dof),
                range_text(&pr.range, lang),
                pr.model.map(|m| model_text(&m, lang)).unwrap_or_else(|| u_of(pr.sd, pr.relative))
            );
        }
        let _ = writeln!(s);
    }

    for b in &t.bias {
        let kind = match b.kind {
            BiasKind::Crm => d.crm,
            BiasKind::ProficiencyTests => d.pt,
            BiasKind::Recovery => d.recovery_exp,
        };
        let _ = writeln!(s, "## {}: {} ({kind})\n", d.bias, b.name);
        let _ = writeln!(s, "| {} | {} | u(C_ref) | s | n |\n|---|---:|---:|---:|---:|", d.reference, d.bias_col);
        for e in &b.entries {
            let _ = writeln!(
                s,
                "| {} | {} | {} | {} | {} |",
                e.label,
                u_of(e.bias, b.relative),
                u_of(e.u_reference, b.relative),
                e.sd.map(|x| u_of(x, b.relative)).unwrap_or_else(|| "—".into()),
                e.n.map(|x| x.to_string()).unwrap_or_else(|| "—".into())
            );
        }
        let _ = writeln!(s, "\n- {}: {}", d.mean_bias, u_of(b.mean_bias, b.relative));
        let _ = writeln!(s, "- {}: {}", d.rms, u_of(b.rms_bias, b.relative));
        let _ = writeln!(s, "- {}: {}", d.mean_uref, u_of(b.mean_u_reference, b.relative));
        let f = if b.single_reference { d.single } else { d.rms_formula };
        let _ = writeln!(s, "- {f} = **{}**\n", u_of(b.u, b.relative));
    }

    if let Some(r) = &t.recovery {
        let _ = writeln!(s, "## {}: {}\n", d.recovery, r.name);
        let _ = writeln!(s, "| {} | R | u(R) |\n|---|---:|---:|", d.test);
        for e in &r.entries {
            let _ = writeln!(
                s,
                "| {} | {} | {} |",
                e.label,
                fmt_pct(e.recovery, 4, lang, false),
                fmt_pct(e.u, 3, lang, false)
            );
        }
        let (mean_label, u_label) =
            if r.weighted { (d.weighted_recovery, d.u_weighted) } else { (d.mean_recovery, d.u_recovery) };
        let _ = writeln!(s, "\n- {}: {}", mean_label, fmt_pct(r.mean, 4, lang, false));
        let _ = writeln!(s, "- {}: {}", u_label, fmt_pct(r.u_mean, 3, lang, false));
        if let Some(sd) = r.sd_of_recoveries {
            let _ = writeln!(s, "- {}: {}", d.sd_recoveries, fmt_pct(sd, 3, lang, false));
        }
        if (r.u_used - r.u_mean).abs() > 0.0 {
            let _ = writeln!(s, "- {}: {}", d.u_used, fmt_pct(r.u_used, 3, lang, false));
        }
        let cmp = if r.significant { ">" } else { "≤" };
        let _ = writeln!(
            s,
            "- {}: |1 − R̄|/u = {} {cmp} t = {} (ν = {}, {}): {}; {}.",
            d.significance,
            n3(r.statistic),
            n3(r.critical),
            dof(r.dof),
            fmt_pct(r.confidence, 3, lang, true),
            if r.significant { d.significant } else { d.not_significant },
            if r.corrected { d.corrected } else { d.not_corrected }
        );
        if let Some(h) = &r.homogeneity {
            let cmp = if h.equivalent { "≤" } else { ">" };
            let _ = writeln!(
                s,
                "- {} (χ²): χ² = {} {cmp} χ²_crit = {}: {}.",
                d.homogeneity,
                n3(h.chi_squared),
                n3(h.critical),
                if h.equivalent { d.equivalent } else { d.not_equivalent }
            );
        }
        let _ = writeln!(s);
    }

    let _ = writeln!(s, "## {}\n", d.budget);
    let _ = writeln!(
        s,
        "| {} | {} | {} | {} | {} |\n|---|---|---:|---:|---|",
        d.component, d.kind, l.std_unc, d.multiplicity, d.range
    );
    for b in &t.budget {
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} |",
            b.name,
            if b.relative { d.relative } else { d.absolute },
            b.model.map(|m| model_text(&m, lang)).unwrap_or_else(|| u_of(b.u, b.relative)),
            b.multiplicity,
            range_text(&b.range, lang)
        );
    }
    let _ = writeln!(s);

    let _ = writeln!(s, "## {}\n", d.results);
    let k = fmt_num(t.coverage_factor, 3, lang);
    let corrected = t.recovery.as_ref().is_some_and(|r| r.corrected);
    let absolute = t.levels.iter().any(|x| x.level.is_some());
    if absolute {
        let _ = writeln!(
            s,
            "| {} | {} | u_c | U (k = {k}) | {} |\n|---:|---:|---:|---:|---:|",
            d.level, d.result, d.exp_rel
        );
    } else {
        let _ = writeln!(s, "| {} | {} (k = {k}) |\n|---:|---:|", d.u_rel, d.exp_rel);
    }
    for lv in &t.levels {
        match (lv.level, lv.value, lv.standard_uncertainty, lv.expanded_uncertainty) {
            (Some(x), Some(v), Some(u), Some(big)) => {
                let _ = writeln!(
                    s,
                    "| {} | {} | {} | {} | {} |",
                    fmt_given(x, lang),
                    fmt_num(v, 5, lang),
                    n3(u),
                    n3(big),
                    fmt_pct(lv.relative_expanded, 3, lang, false)
                );
            }
            _ => {
                let _ = writeln!(
                    s,
                    "| {} | {} |",
                    fmt_pct(lv.relative_standard, 3, lang, false),
                    fmt_pct(lv.relative_expanded, 3, lang, false)
                );
            }
        }
    }
    let _ = writeln!(s);
    if corrected {
        let _ = writeln!(s, "{}\n", d.corrected_note);
    }
    let _ = writeln!(s, "**{}:**\n", l.reported);
    for st in topdown_statements(p, t, lang) {
        let _ = writeln!(s, "- {st}");
    }
    let _ = writeln!(s);
    if t.budget.len() > 1 {
        let _ = writeln!(s, "## {}\n", d.shares);
        let heads: Vec<String> = t
            .levels
            .iter()
            .map(|lv| {
                lv.level.map(|x| format!("{}{unit}", fmt_given(x, lang))).unwrap_or_else(|| d.relative.to_string())
            })
            .collect();
        let _ = writeln!(s, "| {} | {} |", d.component, heads.join(" | "));
        let _ = writeln!(s, "|---|{}", "---:|".repeat(heads.len()));
        for (i, b) in t.budget.iter().enumerate() {
            let cells: Vec<String> = t
                .levels
                .iter()
                .map(|lv| {
                    lv.shares
                        .iter()
                        .find(|(j, _)| *j == i)
                        .map(|(_, sh)| fmt_pct(*sh, 3, lang, false))
                        .unwrap_or_else(|| "—".into())
                })
                .collect();
            let _ = writeln!(s, "| {} | {} |", b.name, cells.join(" | "));
        }
        let _ = writeln!(s);
    }
    tail(
        &mut s,
        p,
        checks,
        lang,
        "Nordtest TR 537 ed. 4 (2017); Eurachem/CITAC MUPR (2026); JCGM 100:2008 (GUM)",
        generated,
    );
    s
}

fn esc(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

/// Horizontal bar chart of variance shares (SVG).
fn contributions_svg(rows: &[(&str, f64)], lang: Lang) -> Option<String> {
    let mut rows: Vec<(&str, f64)> = rows.iter().copied().filter(|r| r.1 > 0.0).collect();
    if rows.is_empty() {
        return None;
    }
    rows.sort_by(|x, y| y.1.total_cmp(&x.1));
    let (w, row_h, left) = (640.0, 26.0, 150.0);
    let h = row_h * rows.len() as f64 + 20.0;
    let max = rows[0].1.max(1e-300);
    let mut s = format!(
        r#"<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="{}" xmlns="http://www.w3.org/2000/svg">"#,
        esc(labels(lang).contributions_chart)
    );
    for (i, (name, share)) in rows.iter().enumerate() {
        let y = 10.0 + i as f64 * row_h;
        let bw = (w - left - 70.0) * share / max;
        let _ = write!(
            s,
            r#"<text x="{}" y="{}" text-anchor="end" class="lbl">{}</text><rect x="{left}" y="{}" width="{bw:.1}" height="{}" class="bar"/><text x="{:.1}" y="{}" class="val">{}</text>"#,
            left - 8.0,
            y + row_h * 0.62,
            esc(name),
            y + 3.0,
            row_h - 8.0,
            left + bw + 6.0,
            y + row_h * 0.62,
            fmt_pct(*share, 3, lang, false)
        );
    }
    s.push_str("</svg>");
    Some(s)
}

/// MCM histogram with the GUM PDF overlaid and both coverage intervals (SVG).
fn histogram_svg(a: &Analysis, lang: Lang) -> Option<String> {
    let m = a.mcm.as_ref()?;
    let hist = &m.histogram;
    let total = m.trials as f64;
    let nb = hist.counts.len();
    if nb == 0 || hist.bin_width <= 0.0 {
        return None;
    }
    let x0 = hist.lower;
    let x1 = hist.lower + hist.bin_width * nb as f64;
    let dens: Vec<f64> = hist.counts.iter().map(|&c| c as f64 / (total * hist.bin_width)).collect();
    let gum_pdf = |x: f64| -> f64 {
        a.gum.as_ref().map_or(0.0, |g| {
            let u = g.combined_standard_uncertainty;
            if u <= 0.0 {
                return 0.0;
            }
            let z = (x - g.estimate) / u;
            if g.effective_dof.is_finite() {
                student_t_pdf(z, g.effective_dof) / u
            } else {
                normal_pdf(z) / u
            }
        })
    };
    let ymax = dens
        .iter()
        .cloned()
        .fold(0.0, f64::max)
        .max((0..=200).map(|i| gum_pdf(x0 + (x1 - x0) * i as f64 / 200.0)).fold(0.0, f64::max));
    if ymax.is_nan() || ymax <= 0.0 {
        return None;
    }
    let (w, h, pad, top) = (640.0, 330.0, 30.0, 72.0);
    let sx = |x: f64| pad + (x - x0) / (x1 - x0) * (w - 2.0 * pad);
    let sy = |y: f64| h - pad - y / ymax * (h - pad - top);
    let l = labels(lang);
    let mut s = format!(
        r#"<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="{}" xmlns="http://www.w3.org/2000/svg">"#,
        esc(l.histogram_chart)
    );
    for (i, d) in dens.iter().enumerate() {
        let xa = sx(x0 + i as f64 * hist.bin_width);
        let xb = sx(x0 + (i + 1) as f64 * hist.bin_width);
        let _ = write!(
            s,
            r#"<rect x="{xa:.2}" y="{:.2}" width="{:.2}" height="{:.2}" class="hist"/>"#,
            sy(*d),
            (xb - xa).max(0.5),
            sy(0.0) - sy(*d)
        );
    }
    if a.gum.is_some() {
        let pts: Vec<String> = (0..=200)
            .map(|i| {
                let x = x0 + (x1 - x0) * i as f64 / 200.0;
                format!("{:.2},{:.2}", sx(x), sy(gum_pdf(x)))
            })
            .collect();
        let _ = write!(s, r#"<polyline points="{}" class="pdf"/>"#, pts.join(" "));
    }
    let (lo, hi) = m.interval(a.interval_kind);
    for x in [lo, hi] {
        if x >= x0 && x <= x1 {
            let _ = write!(s, r#"<line x1="{0:.2}" x2="{0:.2}" y1="{1}" y2="{2}" class="mcm"/>"#, sx(x), top, h - pad);
        }
    }
    if let Some(g) = &a.gum {
        for x in [g.interval.0, g.interval.1] {
            if x >= x0 && x <= x1 {
                let _ = write!(
                    s,
                    r#"<line x1="{0:.2}" x2="{0:.2}" y1="{1}" y2="{2}" class="gumline"/>"#,
                    sx(x),
                    top,
                    h - pad
                );
            }
        }
    }
    let _ = write!(
        s,
        r#"<line x1="{pad}" x2="{xr}" y1="{yb}" y2="{yb}" class="axis"/><text x="{pad}" y="{yt}" class="lbl">{lo}</text><text x="{xr}" y="{yt}" text-anchor="end" class="lbl">{hi}</text>"#,
        xr = w - pad,
        yb = h - pad,
        yt = h - 8.0,
        lo = esc(&fmt_num(x0, 5, lang)),
        hi = esc(&fmt_num(x1, 5, lang))
    );
    let kind = match a.interval_kind {
        IntervalKind::Shortest => l.shortest,
        IntervalKind::Symmetric => l.symmetric,
    };
    let _ = write!(
        s,
        r#"<g class="legend"><rect x="{}" y="10" width="12" height="12" class="hist"/><text x="{}" y="20" class="lbl">MCM</text><line x1="{}" x2="{}" y1="34" y2="34" class="pdf"/><text x="{}" y="38" class="lbl">{}</text><line x1="{}" x2="{}" y1="52" y2="52" class="mcm"/><text x="{}" y="56" class="lbl">{}</text></g>"#,
        w - 230.0,
        w - 212.0,
        w - 230.0,
        w - 218.0,
        w - 212.0,
        l.gum_pdf,
        w - 230.0,
        w - 218.0,
        w - 212.0,
        esc(kind)
    );
    s.push_str("</svg>");
    Some(s)
}

