/// Self-contained HTML report with charts.
pub fn html(p: &Project, a: &Analysis, lang: Lang, generated: Option<&str>) -> String {
    let l = labels(lang);
    let body = md_to_html(&markdown(p, a, lang, generated));
    let mut figures = String::new();
    if let Some(svg) = contributions_svg(a, lang) {
        let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(l.contributions_chart));
    }
    if let Some(svg) = histogram_svg(a, lang) {
        let _ = write!(figures, "<figure><figcaption>{}</figcaption>{svg}</figure>", esc(l.histogram_chart));
    }
    // Place the figures before the Monte Carlo section (or before the sources).
    let anchor = format!("<h2>{}</h2>", esc(l.mcm));
    let body = if let Some(i) = body.find(&anchor) {
        format!("{}{figures}{}", &body[..i], &body[i..])
    } else if let Some(i) = body.find(&format!("<h2>{}</h2>", esc(l.sources))) {
        format!("{}{figures}{}", &body[..i], &body[i..])
    } else {
        format!("{body}{figures}")
    };
    let html_lang = match lang {
        Lang::En => "en",
        Lang::Tr => "tr",
    };
    format!(
        "<!doctype html>\n<html lang=\"{html_lang}\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>{}</title><style>{CSS}</style></head><body><main>\n{body}</main></body></html>\n",
        esc(p.metadata.title.get(lang))
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn number_formatting() {
        assert_eq!(fmt_num(1002.69972, 6, Lang::En), "1002.70");
        assert_eq!(fmt_num(1002.69972, 6, Lang::Tr), "1002,70");
        assert_eq!(fmt_num(0.00058, 2, Lang::En), "0.00058");
        assert_eq!(fmt_num(0.000058, 2, Lang::En), "5.8 × 10⁻⁵");
        assert_eq!(fmt_num(2.5e-7, 2, Lang::En), "2.5 × 10⁻⁷");
        assert_eq!(fmt_num(f64::INFINITY, 3, Lang::En), "∞");
        assert_eq!(fmt_num(50_000_838.0, 8, Lang::En), "5.0000838 × 10⁷");
        assert_eq!(fmt_num(9.999, 3, Lang::En), "10.0");
        assert_eq!(fmt_given(0.05, Lang::Tr), "0,05");
        assert_eq!(fmt_given(2.5e-7, Lang::En), "2.5 × 10⁻⁷");
        assert_eq!(fmt_pct(0.9545, 4, Lang::Tr, true), "%95,45");
        assert_eq!(fmt_pct(0.95, 4, Lang::En, true), "95 %");
    }

    #[test]
    fn markdown_to_html_subset() {
        let h = md_to_html(
            "# T\n\n| a | b |\n|---|---|\n| 1 | **2** |\n\n- x\n- y\n\n1. one\n2. two\n\n```\nc = a*b\n```\n",
        );
        assert!(h.contains("<h1>T</h1>"));
        assert!(h.contains("<th>a</th>") && h.contains("<td><strong>2</strong></td>"));
        assert!(h.contains("<ul>") && h.contains("<ol>"));
        assert!(h.contains("<pre>c = a*b\n</pre>"));
    }
}
