"""Writes docs/research/findings-index.md from the research log: every finding (F) and decision (D) with its
title and the session in which it was recorded. Run from the repository root after adding log entries."""
import re
from pathlib import Path

log = Path("docs/research/research-log.md").read_text(encoding="utf-8").splitlines()
session = ""
entries = {"F": [], "D": []}
i = 0
while i < len(log):
    line = log[i]
    if line.startswith("## "):
        session = line[3:].strip()
    m = re.match(r"^\*\*([FD])(\d+)\.\s*(.*)", line)
    if m:
        text = m.group(3)
        j = i
        while "**" not in text and j + 1 < len(log) and log[j + 1].strip():
            j += 1
            text += " " + log[j].strip()
        title = text.split("**")[0].strip()
        entries[m.group(1)].append((int(m.group(2)), title, session))
    i += 1

out = ["# Index of findings and decisions",
       "",
       "Generated by `tools/research/findings_index.py` from `research-log.md`, which holds the full text. An",
       "entry listed more than once was resolved or extended in a later session.",
       "",
       "Classes of findings (D12):",
       "",
       "- **a**: intermediate rounding, a legitimate practice;",
       "- **b**: a typographical or transcription slip without effect on the result;",
       "- **c**: an inconsistency affecting a printed result.",
       "",
       "Corrections to a class are recorded in later log entries; the latest one applies.",
       "",
       f"## Findings ({len({n for n, _, _ in entries['F']})})",
       "",
       "| F | Finding | Session |",
       "|---|---|---|"]
for n, t, s in sorted(entries["F"], key=lambda e: e[0]):
    out.append(f"| F{n} | {t.replace('|', '/')} | {s} |")
out += ["", f"## Decisions ({len({n for n, _, _ in entries['D']})})", "", "| D | Decision | Session |", "|---|---|---|"]
for n, t, s in sorted(entries["D"], key=lambda e: e[0]):
    out.append(f"| D{n} | {t.replace('|', '/')} | {s} |")
Path("docs/research/findings-index.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(entries["F"]), "finding entries,", len(entries["D"]), "decision entries")
