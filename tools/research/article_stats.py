"""Summary numbers for the article: library projects by section, field and source document; findings by class;
validation-matrix rows. Run from the repository root; writes docs/article/numbers.md."""
import collections
import glob
import json
import re
from pathlib import Path

SECTIONS = ("model", "topdown", "proficiency", "calibration", "precision_experiment", "multivariate", "control_chart",
            "sampling", "error_function", "multicomponent_conformity", "consensus")
sec, field, docs = collections.Counter(), collections.Counter(), collections.Counter()
mcm = 0
for f in sorted(glob.glob("library/*/*.json")):
    p = json.loads(Path(f).read_text(encoding="utf-8"))
    s = next((k for k in SECTIONS if k in p), "conformity")
    if s == "model" and "conformity" in p:
        s = "model + conformity"
    sec[s] += 1
    field[p["metadata"].get("field", "")] += 1
    for src in p["metadata"].get("sources", []):
        d = src["document"].split(",")[0].split(" (")[0].strip()
        docs[d] += 1
    if (p.get("analysis") or {}).get("mcm") is not None and s.startswith("model"):
        mcm += 1

log = Path("docs/research/research-log.md").read_text(encoding="utf-8")
FAMILIES = [("GUM-5", "JCGM GUM-5:2026"), ("JCGM 101", "JCGM 101"), ("JCGM 102", "JCGM 102"), ("JCGM 106", "JCGM 106"),
            ("GUM", "JCGM 100 (GUM)"), ("TR 537", "Nordtest TR 537"), ("Nordtest §", "Nordtest TR 537"),
            ("Nordtest Appendix", "Nordtest TR 537"), ("TR 569", "Nordtest TR 569"), ("MUPR", "Eurachem MUPR"),
            ("EURACHEM", "Eurachem QUAM"), ("QUAM", "Eurachem QUAM"), ("EA-4/02", "EA-4/02"), ("TN 1900", "NIST TN 1900"),
            ("NUM", "NIST Uncertainty Machine"), ("ISO 13528", "ISO 13528"), ("ISO 21748", "ISO 21748"),
            ("ISO 5725", "ISO 5725"), ("ISO 6143", "ISO 6143"), ("M3003", "UKAS M3003"), ("cg-18", "EURAMET cg-18"),
            ("cg-19", "EURAMET cg-19"), ("UfS", "Eurachem UfS"), ("RANOVA", "Eurachem UfS"), ("Bettencourt", "Bettencourt da Silva 2026"),
            ("Magnusson", "Magnusson & Ellison 2008"), ("Mateos", "Mateos et al. 2020"), ("Delker", "Delker 2021"),
            ("EMUE", "EMPIR EMUE"), ("IUPAC", "IUPAC 2024"), ("Koepke", "Koepke et al. 2017"),
            ("Possolo & Meija", "Possolo & Meija 2022"), ("BIPM ISRD", "BIPM ISRD"), ("compliance guide", "Eurachem/CITAC compliance 2021"),
            ("Second-order", "methodological"), ("Shortest", "methodological"), ("Two conventions", "methodological"),
            ("Bimodal", "ISO 13528"), ("Guidance documents", "summary"), ("Overall picture", "summary")]
classes = collections.Counter()
by_doc = collections.defaultdict(collections.Counter)
for line in Path("docs/research/finding-classes.tsv").read_text(encoding="utf-8").splitlines()[1:]:
    f, cl, _doc, title = line.split("\t")
    classes[cl] += 1
    fam = next((name for key, name in FAMILIES if key in title), "other")
    for c in cl.split(","):
        by_doc[fam][c] += 1
rows = [l for l in Path("docs/research/validation-matrix.md").read_text(encoding="utf-8").splitlines() if l.startswith("| ") and "✅" in l]
exc = [l for l in rows if "except" in l or "; F" in l]

out = ["# Numbers for the article", "", "Generated by `tools/research/article_stats.py`; do not edit by hand.", "",
       f"- Library projects: **{sum(sec.values())}**; model projects with a Monte Carlo evaluation: {mcm}.",
       f"- Validation-matrix rows marked ✅: **{len(rows)}**, of which {len(exc)} carry a finding.",
       f"- Findings F1–F{max(int(x) for x in re.findall(r'^\*\*F(\d+)\.', log, re.M))}; by class (`finding-classes.tsv`, D12/D73): "
       + ", ".join(f"{k}: {v}" for k, v in sorted(classes.items())) + "; findings with a class c component: "
       + str(sum(v for k, v in classes.items() if "c" in k)) + ".",
       "", "## Projects by section", "", "| Section | Projects |", "|---|---:|"]
out += [f"| {k} | {v} |" for k, v in sec.most_common()]
out += ["", "## Projects by field", "", "| Field | Projects |", "|---|---:|"]
out += [f"| {k} | {v} |" for k, v in field.most_common()]
out += ["", "## Findings by document and class (a finding with two classes counts in both)", "",
        "| Document | a | b | c | n |", "|---|---:|---:|---:|---:|"]
out += [f"| {d} | {c['a']} | {c['b']} | {c['c']} | {c['n']} |" for d, c in sorted(by_doc.items(), key=lambda x: -sum(x[1].values()))]
out += ["", f"## Source documents ({len(docs)})", "", "| Document (first part of the citation) | Projects |", "|---|---:|"]
out += [f"| {k} | {v} |" for k, v in docs.most_common()]
Path("docs/article").mkdir(exist_ok=True)
Path("docs/article/numbers.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[:8]))
print("documents:", len(docs))
